from pathlib import Path

from inline_snapshot import snapshot

from documator.domain import InputDir, OutputDir, TimeoutSeconds
from documator.render import render
from documator.skills import skills
from documator.tree_layout import TreeLayout, build_tree


def _render(input_dir: Path, output_dir: Path) -> int:
    return render(InputDir(input_dir), OutputDir(output_dir), TimeoutSeconds(10.0))


def _skills(input_dir: Path, output_dir: Path) -> int:
    return skills(InputDir(input_dir), OutputDir(output_dir), TimeoutSeconds(10.0))


def test_an_attachment_link_follows_the_flattened_bundle(tmp_path: Path) -> None:
    build_tree(
        tmp_path,
        TreeLayout("""
            in
              guides
                @plan
                  SKILL.md | see [[diagram.png]] for the shape\\n
                  assets
                    diagram.png | not really a png\\n
            out
        """),
    )

    assert _skills(tmp_path / "in", tmp_path / "out") == 0

    assert (tmp_path / "out" / "plan" / "SKILL.md").read_text() == snapshot("""\
---
name: plan
description: plan
---
<!-- Generated by documator from guides/@plan/SKILL.md — edit the template, not this file. -->
see [diagram](assets/diagram.png) for the shape
""")


def test_an_attachment_outside_the_bundle_has_nowhere_to_land(tmp_path: Path) -> None:
    build_tree(
        tmp_path,
        TreeLayout("""
            in
              assets
                diagram.png | not really a png\\n
              guides
                @plan
                  SKILL.md | see [[diagram.png]] for the shape\\n
            out
        """),
    )

    assert _skills(tmp_path / "in", tmp_path / "out") == 1

    assert (tmp_path / "out" / "plan" / "SKILL.md").read_text() == snapshot("""\
---
name: plan
description: plan
---
<!-- Generated by documator from guides/@plan/SKILL.md — edit the template, not this file. -->
see [[diagram.png]] [documator: link to assets/diagram.png, which this run does not emit] for the shape
""")


