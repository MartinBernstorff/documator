def test_a_link_a_command_prints_is_data_rather_than_a_link(tmp_path: Path) -> None:
    build_tree(
        tmp_path,
        TreeLayout("""
            in
              index.md | ```\\n!echo '[[Tracer bullet]]'\\n```\\n
              Tracer bullet.md | a thin vertical slice\\n
            out
        """),
    )

    assert _render(tmp_path / "in", tmp_path / "out") == 0

    # Spelled with escapes rather than snapshotted: what a command prints is neutralized
    # on the way out, so the brackets it survives as are holding zero-width spaces.
    assert (tmp_path / "out" / "index.md").read_text().splitlines()[2] == (
        "[\u200b[Tracer bullet]\u200b]"
    )


